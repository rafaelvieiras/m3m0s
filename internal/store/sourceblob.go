package store

import (
	"crypto/sha256"
	"encoding/hex"
)

// metadataKeySourceContentRef is the internal key (never exposed by the 3
// surfaces — HTTP/MCP/CLI, docs/api-contract.md) that replaces the full
// copy of the source text in metadataKeySourceContent with a hash
// reference to the deduplicated source_blobs table (D21,
// docs/decisions/ — fixes A7; ported from sourceblobs.json to SQLite in
// D28). MemoryStore.internalizeMetadata writes here on write;
// MemoryStore.externalizeEntry resolves it back to
// metadataKeySourceContent on every public output, so the API contract
// does not change — only what stays on disk.
const metadataKeySourceContentRef = "source_content_ref"

// sourceBlobPrefix visually identifies a blob hash (vs. an ID generated by
// idgen.New, like "mem_..."/"chunk_...") anywhere it leaks into
// logs/debug.
const sourceBlobPrefix = "src_"

// hashSourceContent uses the full sha256 (not truncated — the key is
// already tiny next to the text it replaces, no reason to risk a collision
// just to save a few more bytes).
func hashSourceContent(text string) string {
	sum := sha256.Sum256([]byte(text))
	return sourceBlobPrefix + hex.EncodeToString(sum[:])
}
